using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace Ecologistics.PickupManagement.Infrastructure.Services;

public record GenerateInvoiceForPickupRequest(
    string PickupReference,
    string WasteContent,
    int NumberOfPackages,
    string WeightForEachPackage,
    string TotalWeight,
    decimal PricePerPackage,
    string PackageSize,
    decimal TotalPrice,
    DateTimeOffset PickupDate,
    string PaymentMethod,
    string CollectorFullName,
    string GeneratorFullName);

public static class GenerateInvoiceForPickupService
{
    public static byte[] Generate(GenerateInvoiceForPickupRequest request)
    {
        QuestPDF.Settings.License = LicenseType.Community;

        return Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Size(PageSizes.A4);
                    page.Margin(2, Unit.Centimetre);
                    page.PageColor(Colors.White);
                    page.DefaultTextStyle(style => style.FontSize(12));

                    page.Header()
                        .Text("Ecologistics")
                        .AlignLeft()
                        .FontFamily("Arial")
                        .Bold()
                        .FontSize(16)
                        .LineHeight(20)
                        .FontColor(Colors.Green.Darken2);

                    page.Content()
                        .PaddingVertical(1, Unit.Centimetre)
                        .Column(column =>
                        {
                            column.Spacing(20);

                            column.Item()
                                .Text($"Invoice for Pickup with Reference #: {request.PickupReference}")
                                .FontSize(14)
                                .Bold()
                                .AlignLeft();
                            column.Spacing(20);

                            column.Item()
                                .Text($"Waste Content: {request.WasteContent}")
                                .FontSize(14);
                            column.Spacing(5);
                            column.Item()
                                .Text($"Number of Packages: {request.NumberOfPackages}")
                                .FontSize(14);
                            column.Spacing(5);
                            column.Item()
                                .Text($"Each Package Size: {request.PackageSize}")
                                .FontSize(14);
                            column.Spacing(5);
                            column.Item()
                                .Text($"Weight per Package: {request.WeightForEachPackage}")
                                .FontSize(14);
                            column.Spacing(5);
                            column.Item()
                                .Text($"Total Weight: {request.TotalWeight}")
                                .FontSize(14);
                            column.Spacing(5);
                            column.Item()
                                .Text($"Pickup scheduled date: {request.PickupDate.Date.ToLongDateString()} and time: {request.PickupDate.TimeOfDay}")
                                .FontSize(14);

                            column.Spacing(20);

                            column.Item()
                                .Text($"Price paid per package: {request.PricePerPackage}")
                                .FontSize(14)
                                .Bold()
                                .AlignRight();
                            column.Spacing(5);
                            column.Item()
                                .Text($"Total Price: {request.TotalPrice}")
                                .FontSize(14)
                                .Bold()
                                .AlignRight();
                            column.Spacing(5);
                            column.Item()
                                .Text($"Payment Method: {request.PaymentMethod}")
                                .FontSize(14)
                                .Bold()
                                .AlignRight();

                            column.Spacing(20);

                            column.Item()
                                .Text($"Collector: {request.CollectorFullName}")
                                .FontSize(14)
                                .Bold()
                                .AlignLeft();
                            column.Spacing(5);
                            column.Item()
                                .Text($"Generated by: {request.GeneratorFullName}")
                                .FontSize(14)
                                .Bold()
                                .AlignLeft();
                        });

                    page.Footer()
                        .Text($"Invoice generated on: {DateTime.Now.ToLongDateString()} and time: {DateTime.Now.TimeOfDay}")
                        .AlignCenter();
                });
            })
        .GeneratePdf();
    }
}
